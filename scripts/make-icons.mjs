// Draw the app icons from the diamond ore sprite (src/lib/pixel/sprites.js).
// Usage: node scripts/make-icons.mjs   (needs Inkscape for the PNG files)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { spriteRuns } from '../src/lib/pixel/sprites.js';

const dir = new URL('../static/app-icons/', import.meta.url).pathname;
const rects = spriteRuns('diamond')
	.map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.width}" height="1" fill="${r.color}"/>`)
	.join('');

// Regular icon: the block with a black outline, like an item in the inventory.
writeFileSync(
	`${dir}icon.svg`,
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="-1 -1 18 18" shape-rendering="crispEdges">
	<!-- Vokabulator: a diamond ore block – generated by scripts/make-icons.mjs -->
	<rect x="-1" y="-1" width="18" height="18" fill="#000"/>${rects}
</svg>
`
);

// Maskable icon (Android cuts it into a circle or squircle): block in the safe zone on dark ground.
writeFileSync(
	`${dir}icon-maskable.svg`,
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="-4 -4 24 24" shape-rendering="crispEdges">
	<!-- Vokabulator (maskable): diamond ore block on dark ground – generated by scripts/make-icons.mjs -->
	<rect x="-4" y="-4" width="24" height="24" fill="#241a12"/><rect x="-1" y="-1" width="18" height="18" fill="#000"/>${rects}
</svg>
`
);

/** @param {string} svg @param {string} png @param {number} size */
const render = (svg, png, size) =>
	execFileSync('inkscape', [
		`${dir}${svg}`,
		'-w',
		String(size),
		'-h',
		String(size),
		'-o',
		`${dir}${png}`
	]);

render('icon.svg', 'icon-192.png', 192);
render('icon.svg', 'icon-512.png', 512);
render('icon-maskable.svg', 'icon-maskable-512.png', 512);
render('icon-maskable.svg', 'apple-touch-icon.png', 180);
console.log('icons written to static/app-icons/');
